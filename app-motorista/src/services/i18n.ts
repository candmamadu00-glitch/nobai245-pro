i18n.on('languageChanged', (lng: string) => {
  const normalized = lng === 'gnb' ? 'cri' : lng;
  AsyncStorage.setItem(LANGUAGE_KEY, normalized).catch(() => {});
  AsyncStorage.setItem(LEGACY_LANGUAGE_KEY, normalized).catch(() => {});
});

export const loadSavedLanguage = async () => {
  try {
    const saved =
      (await AsyncStorage.getItem(LANGUAGE_KEY)) ||
      (await AsyncStorage.getItem(LEGACY_LANGUAGE_KEY));
    if (saved) {
      const normalized = saved === 'gnb' ? 'cri' : saved;
      if (normalized !== i18n.language) {
        await i18n.changeLanguage(normalized);
      }
    }
  } catch (error) {
    console.warn('Erro ao carregar idioma salvo:', error);
  }
};

loadSavedLanguage();

export const changeLanguage = async (languageCode: string) => {
  const normalized = languageCode === 'gnb' ? 'cri' : languageCode;
  await AsyncStorage.setItem(LANGUAGE_KEY, normalized);
  await AsyncStorage.setItem(LEGACY_LANGUAGE_KEY, normalized);
  await i18n.changeLanguage(normalized);
};

